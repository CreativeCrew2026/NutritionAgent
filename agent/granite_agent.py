FORBIDDEN_PATTERNS = [
    r"stop (taking|using) (your )?(medication|medicine|insulin|drug)",
    r"replace (your )?(doctor|physician|specialist)",
    r"cure (diabetes|cancer|hypertension|disease)",
    r"guaranteed (weight loss|cure|result)",
    r"(detox|cleanse) (your|the) (liver|kidney|body)",
    r"miracle (food|diet|supplement)",
    r"(lose|drop) \d+ (kg|lbs|pounds) in \d+ (day|week)",
    r"starve yourself",
    r"(unsafe|dangerous) (fasting|restriction)",
]

COMPILED_GUARDS = [re.compile(p, re.IGNORECASE) for p in FORBIDDEN_PATTERNS]


def _apply_guardrails(text: str) -> tuple[str, list[str]]:
    """Screen output for harmful content and return cleaned text + warnings."""
    warnings = []
    for pattern in COMPILED_GUARDS:
        if pattern.search(text):
            warnings.append(f"Guardrail triggered: '{pattern.pattern}'")
            text = pattern.sub("[CONTENT REMOVED BY SAFETY FILTER]", text)
    return text, warnings


