# ──────────────────────────────────────────────
#  IBM Granite LLM wrapper
# ──────────────────────────────────────────────

class GraniteNutritionAgent:
    """
    Agentic AI wrapper around IBM Granite LLM.
    Implements the ReAct (Reason + Act) pattern with guardrails.
    """

    def __init__(self):
        self.model = None
        self.is_mock = False
        self._init_model()

    def _init_model(self):
        """Initialise IBM Granite via watsonx.ai SDK."""
        api_key = os.getenv("WATSONX_API_KEY", "")
        project_id = os.getenv("WATSONX_PROJECT_ID", "")
        url = os.getenv("WATSONX_URL", "https://us-south.ml.cloud.ibm.com")

        if not _WATSONX_AVAILABLE:
            print("[Agent] ibm-watsonx-ai not installed — running in demo mode.")
            self.is_mock = True
            return

        if not api_key or api_key == "your_ibm_cloud_api_key_here":
            print("[Agent] No valid API key found — running in demo mode.")
            self.is_mock = True
            return

        try:
            credentials = Credentials(url=url, api_key=api_key)
            params = {
                GenParams.MAX_NEW_TOKENS: 2048,
                GenParams.MIN_NEW_TOKENS: 50,
                GenParams.TEMPERATURE: 0.6,
                GenParams.TOP_P: 0.9,
                GenParams.TOP_K: 50,
                GenParams.REPETITION_PENALTY: 1.1,
            }
            self.model = ModelInference(
                model_id=GRANITE_MODEL_ID,
                credentials=credentials,
                project_id=project_id,
                params=params,
            )
            print(f"[Agent] IBM Granite model '{GRANITE_MODEL_ID}' initialised successfully.")
        except Exception as e:
            print(f"[Agent] Failed to initialise Granite model: {e} — falling back to demo mode.")
            self.is_mock = True

    def _call_granite(self, prompt: str) -> str:
        """Send a prompt to IBM Granite and return the response text."""
        if self.is_mock or self.model is None:
            return self._mock_response(prompt)

        full_prompt = f"<|system|>\n{_build_system_prompt()}\n<|user|>\n{prompt}\n<|assistant|>\n"
        try:
            response = self.model.generate_text(prompt=full_prompt)
            return response
        except Exception as e:
            print(f"[Agent] Granite API error: {e}")
            return self._mock_response(prompt)

    def _mock_response(self, prompt: str) -> str:
        """Return a rich demo response when no API key is configured."""
        if "7-Day Meal Plan" in prompt or "nutrition plan" in prompt.lower():
            return _DEMO_NUTRITION_PLAN
        return _DEMO_QUERY_RESPONSE

    # ── Public agentic methods ──────────────────

    def generate_nutrition_plan(self, user_data: dict) -> dict:
        """
        Agentic pipeline:
          Plan → Retrieve context → Generate → Guardrail → Reflect → Output
        """
        # PHASE 1: Plan
        print(f"[Agent] Planning nutrition analysis for {user_data.get('name', 'user')}...")

        # PHASE 2: Build prompt
        prompt = _build_nutrition_prompt(user_data)

        # PHASE 3: Generate with Granite
        print("[Agent] Generating plan with IBM Granite LLM...")
        raw_output = self._call_granite(prompt)

        # PHASE 4: Apply guardrails
        safe_output, warnings = _apply_guardrails(raw_output)
        if warnings:
            print(f"[Agent] Guardrails triggered: {warnings}")

        # PHASE 5: Append disclaimer
        final_output = safe_output + MEDICAL_DISCLAIMER

        # PHASE 6: Reflect & return structured response
        return {
            "status": "success",
            "plan": final_output,
            "user_name": user_data.get("name", "User"),
            "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "model": GRANITE_MODEL_ID if not self.is_mock else "demo-mode",
            "guardrail_warnings": warnings,
            "is_demo": self.is_mock,
        }

    def answer_query(self, query: str, user_context: dict | None = None) -> dict:
        """Answer a standalone nutrition query with optional user context."""
        # Guardrail check on input
        _, input_warnings = _apply_guardrails(query)
        if input_warnings:
            return {
                "status": "blocked",
                "answer": "Your query contains content that could promote unsafe practices. "
                          "Please consult a registered healthcare professional.",
                "warnings": input_warnings,
            }

        prompt = _build_query_prompt(query, user_context)
        raw_output = self._call_granite(prompt)
        safe_output, warnings = _apply_guardrails(raw_output)

        return {
            "status": "success",
            "answer": safe_output,
            "query": query,
            "model": GRANITE_MODEL_ID if not self.is_mock else "demo-mode",
            "guardrail_warnings": warnings,
            "is_demo": self.is_mock,
        }


